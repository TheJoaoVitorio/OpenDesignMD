import { Company, ExportFormat } from "../types.js";

export interface ExportResult {
  content: string;
  contentType: string;
  filename: string;
}

export class ExportService {
  /**
   * Generates formatted design tokens according to the requested export target
   */
  public export(company: Company, format: ExportFormat): ExportResult {
    switch (format) {
      case "tailwind-v4":
        return this.exportTailwindV4(company);
      case "tailwind-v3":
        return this.exportTailwindV3(company);
      case "dtcg":
        return this.exportDtcg(company);
      case "design-md":
      default:
        return this.exportDesignMd(company);
    }
  }

  /**
   * Tailwind CSS v4 CSS @theme Block
   */
  private exportTailwindV4(company: Company): ExportResult {
    const lines: string[] = [];
    lines.push(`/* Tailwind CSS v4 Theme Configuration for ${company.name} */`);
    lines.push(`/* Generated by OpenDesignMD (@google/design.md spec) */`);
    lines.push(`@theme {`);

    // Colors
    for (const [key, val] of Object.entries(company.colors)) {
      if (val && typeof val === "string") {
        const kebabKey = this.toKebabCase(key);
        lines.push(`  --color-${kebabKey}: ${val};`);
      }
    }

    lines.push(``);

    // Typography
    if (company.typography.fontFamily) {
      lines.push(`  --font-sans: ${company.typography.fontFamily};`);
    }
    if (company.typography.monoFamily) {
      lines.push(`  --font-mono: ${company.typography.monoFamily};`);
    }

    lines.push(``);

    // Radii
    for (const [key, val] of Object.entries(company.rounded || {})) {
      lines.push(`  --radius-${key}: ${val};`);
    }

    lines.push(``);

    // Spacing
    for (const [key, val] of Object.entries(company.spacing || {})) {
      lines.push(`  --spacing-${key}: ${val};`);
    }

    lines.push(`}`);

    return {
      content: lines.join("\n"),
      contentType: "text/css; charset=utf-8",
      filename: `${company.id}-theme.css`,
    };
  }

  /**
   * Tailwind CSS v3 JavaScript JSON Configuration
   */
  private exportTailwindV3(company: Company): ExportResult {
    const colorsObj: Record<string, string> = {};
    for (const [key, val] of Object.entries(company.colors)) {
      if (val && typeof val === "string") {
        colorsObj[this.toKebabCase(key)] = val;
      }
    }

    const sansFonts = company.typography.fontFamily
      ? company.typography.fontFamily.split(",").map((s) => s.replace(/['"]/g, "").trim())
      : ["Inter", "sans-serif"];

    const monoFonts = company.typography.monoFamily
      ? company.typography.monoFamily.split(",").map((s) => s.replace(/['"]/g, "").trim())
      : ["monospace"];

    const config = {
      theme: {
        extend: {
          colors: colorsObj,
          fontFamily: {
            sans: sansFonts,
            mono: monoFonts,
          },
          borderRadius: company.rounded || {},
          spacing: company.spacing || {},
        },
      },
    };

    return {
      content: JSON.stringify(config, null, 2),
      contentType: "application/json; charset=utf-8",
      filename: `${company.id}-tailwind.config.json`,
    };
  }

  /**
   * Official W3C Design Tokens Community Group (DTCG) standard format
   */
  private exportDtcg(company: Company): ExportResult {
    const colorTokens: Record<string, { $value: string; $type: string }> = {};
    for (const [key, val] of Object.entries(company.colors)) {
      if (val && typeof val === "string") {
        colorTokens[this.toKebabCase(key)] = {
          $value: val,
          $type: "color",
        };
      }
    }

    const radiusTokens: Record<string, { $value: string; $type: string }> = {};
    for (const [key, val] of Object.entries(company.rounded || {})) {
      radiusTokens[key] = {
        $value: val,
        $type: "dimension",
      };
    }

    const spacingTokens: Record<string, { $value: string; $type: string }> = {};
    for (const [key, val] of Object.entries(company.spacing || {})) {
      spacingTokens[key] = {
        $value: val,
        $type: "dimension",
      };
    }

    const dtcgTokens = {
      $schema: "https://design-tokens.github.io/community-group/format/",
      name: company.name,
      version: "1.0.0",
      color: colorTokens,
      fontFamily: {
        sans: {
          $value: company.typography.fontFamily,
          $type: "fontFamily",
        },
        mono: {
          $value: company.typography.monoFamily || "monospace",
          $type: "fontFamily",
        },
      },
      dimension: {
        radius: radiusTokens,
        spacing: spacingTokens,
      },
    };

    return {
      content: JSON.stringify(dtcgTokens, null, 2),
      contentType: "application/json; charset=utf-8",
      filename: `${company.id}-tokens.json`,
    };
  }

  /**
   * Google Labs DESIGN.MD Raw Markdown
   */
  private exportDesignMd(company: Company): ExportResult {
    return {
      content: company.designMd,
      contentType: "text/markdown; charset=utf-8",
      filename: `${company.id}-DESIGN.MD`,
    };
  }

  private toKebabCase(str: string): string {
    return str
      .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
      .replace(/[\s_]+/g, "-")
      .toLowerCase();
  }
}

export const exportService = new ExportService();
